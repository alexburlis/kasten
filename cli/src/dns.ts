import { zoneOf } from "./config.ts";

import type { KastenConfig } from "./config.ts";

interface DnsRecord {
  readonly name: string;
  readonly type: "A" | "AAAA" | "CNAME" | "MX" | "TXT";
  readonly value: string;
  readonly note: string;
}

function fqdn(name: string): string {
  return name.endsWith(".") ? name : `${name}.`;
}

/**
 * The regions whose SES Easy DKIM records point at `dkim.<region>.amazonses.com`. Every other
 * region uses `dkim.amazonses.com`. Source: AWS General Reference, "Amazon Simple Email Service
 * endpoints and quotas", table "DKIM domains" (https://docs.aws.amazon.com/general/latest/gr/ses.html#ses_dkim_domains),
 * read on 4 November 2026. The SES Developer Guide adds that an identity's SigningHostedZone can
 * differ, so the records SES shows for the identity win (send-email-authentication-dkim-easy-managing).
 */
const REGIONAL_DKIM_DOMAIN: ReadonlySet<string> = new Set([
  "af-south-1",
  "ap-south-2",
  "ap-southeast-3",
  "ap-southeast-5",
  "ca-west-1",
  "ap-northeast-3",
  "eu-south-1",
  "eu-central-2",
  "il-central-1",
  "me-central-1",
  "us-gov-east-1",
]);

/** The Easy DKIM CNAME target domain for an SES region. */
export function sesDkimDomain(region: string): string {
  return REGIONAL_DKIM_DOMAIN.has(region) ? `dkim.${region}.amazonses.com` : "dkim.amazonses.com";
}

/** Quotes a TXT value for a zone file. Values over 255 bytes are split into strings. */
function txt(value: string): string {
  const chunks = value.match(/.{1,255}/gu) ?? [""];

  return chunks
    .map((chunk) => `"${chunk.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`)
    .join(" ");
}

function hostRecords(config: KastenConfig, host: string, purpose: string): DnsRecord[] {
  const records: DnsRecord[] = [
    {
      name: host,
      type: "A",
      value: config.dns.ipv4 ?? "<VPS IPv4 address>",
      note: `${purpose}; IPv4 is required`,
    },
  ];

  if (config.dns.ipv6 !== null) {
    records.push({
      name: host,
      type: "AAAA",
      value: config.dns.ipv6,
      note: `${purpose} over IPv6`,
    });
  }

  return records;
}

function domainRecords(config: KastenConfig, domain: string): DnsRecord[] {
  const region = config.dns.sesRegion;
  const tokens = config.dns.sesDkimTokens[domain];

  const records: DnsRecord[] = [1, 2, 3].map((n) => {
    const token = tokens?.[n - 1] ?? `<SES DKIM token ${n}>`;

    return {
      name: `${token}._domainkey.${domain}`,
      type: "CNAME",
      value: fqdn(`${token}.${sesDkimDomain(region)}`),
      note:
        tokens === undefined
          ? `SES Easy DKIM: copy token ${n} from the SES console`
          : `SES Easy DKIM ${n} of 3`,
    };
  });

  const dmarc = [`v=DMARC1`, `p=${config.dns.dmarcPolicy}`];

  if (config.dns.dmarcReportAddress !== null)
    dmarc.push(`rua=mailto:${config.dns.dmarcReportAddress}`);

  records.push(
    {
      name: domain,
      type: "TXT",
      value: txt("v=spf1 include:amazonses.com -all"),
      note: "SPF: only SES sends for this domain",
    },
    { name: `_dmarc.${domain}`, type: "TXT", value: txt(dmarc.join("; ")), note: "DMARC" },
  );

  if (config.dns.customMailFrom !== null) {
    const bounce = `${config.dns.customMailFrom}.${domain}`;
    records.push(
      {
        name: bounce,
        type: "MX",
        value: `10 ${fqdn(`feedback-smtp.${region}.amazonses.com`)}`,
        note: "SES custom MAIL FROM: bounces come back to SES",
      },
      {
        name: bounce,
        type: "TXT",
        value: txt("v=spf1 include:amazonses.com ~all"),
        note: "SPF for the custom MAIL FROM",
      },
    );
  }

  if (config.dns.tlsRptAddress !== null) {
    records.push({
      name: `_smtp._tls.${domain}`,
      type: "TXT",
      value: txt(`v=TLSRPTv1; rua=mailto:${config.dns.tlsRptAddress}`),
      note: "Optional TLS-RPT: senders report TLS failures to this address",
    });
  }

  return records;
}

function render(records: readonly DnsRecord[], ttl: number): string[] {
  const nameWidth = Math.max(...records.map((r) => fqdn(r.name).length));

  return records.map(
    (r) =>
      `${fqdn(r.name).padEnd(nameWidth)} ${String(ttl).padStart(5)} IN ${r.type.padEnd(5)} ${r.value} ; ${r.note}`,
  );
}

/** The DNS records to create, as zone-file lines that people can paste. */
export function dnsZoneText(config: KastenConfig): string {
  const ttl = config.dns.ttl;

  const lines: string[] = [
    `; DNS records for Kasten, generated by "kasten dns". TTL ${ttl} seconds.`,
    "; Create every record except MX first. Change MX last, when you move your mail in.",
    "; Replace every <...> placeholder before you paste.",
    "; SES Easy DKIM: the CNAME targets follow AWS's region table. Where SES shows another target for a token, use that one.",
    "",
    "; Hosts on the mail VPS",
    ...render(
      [
        ...hostRecords(
          config,
          config.serverHostname,
          "MX host: other mail servers connect here on port 25",
        ),
        ...hostRecords(config, config.mailApiHostname, "Mail API: JMAP and sign-in on port 443"),
      ],
      ttl,
    ),
  ];

  for (const domain of config.domains) {
    lines.push(
      "",
      `; ${domain.name}: sending through SES`,
      ...render(domainRecords(config, domain.name), ttl),
    );
  }

  lines.push("", "; MX: change these last");
  lines.push(
    ...render(
      config.domains.map((domain) => ({
        name: domain.name,
        type: "MX",
        value: `10 ${fqdn(config.serverHostname)}`,
        note: "incoming mail goes to the VPS",
      })),
      ttl,
    ),
  );

  const appHost = new URL(config.webApp.origin).hostname;

  lines.push(
    "",
    `; ${appHost}: the web app. Point it at the app host, never at the mail VPS, and turn any DNS proxy or CDN off for it.`,
  );

  const outside = [config.serverHostname, config.mailApiHostname].filter(
    (host) =>
      zoneOf(
        host,
        config.domains.map((d) => d.name),
      ) === null,
  );

  if (outside.length > 0)
    lines.push(`; Create the host records for ${outside.join(" and ")} in their own zone.`);

  return `${lines.join("\n")}\n`;
}
