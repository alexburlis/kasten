// Collects the npm packages that end up in the bundle and writes their licence texts.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import type { Plugin } from "vite";
import { z } from "zod";

const packageJson = z.object({
  name: z.string(),
  version: z.string(),
  license: z.string().optional(),
  homepage: z.string().optional(),
  repository: z.union([z.string(), z.object({ url: z.string() })]).optional(),
});

export interface BundledPackage {
  readonly name: string;
  readonly version: string;
  readonly license: string;
  readonly source: string | null;
  readonly licenseTexts: readonly string[];
}

/** Packages seen by every build that feeds the app: the page, the key worker and the service worker. */
export class LicenseCollector {
  readonly #dirs = new Set<string>();

  add(moduleId: string): void {
    const dir = packageDir(moduleId);

    if (dir !== null) this.#dirs.add(dir);
  }

  packages(): BundledPackage[] {
    const seen = new Map<string, BundledPackage>();

    for (const dir of this.#dirs) {
      const parsed = packageJson.parse(JSON.parse(readFileSync(join(dir, "package.json"), "utf8")));
      const key = `${parsed.name}@${parsed.version}`;

      if (seen.has(key)) continue;

      const texts = licenseFiles(dir).map((file) => readFileSync(join(dir, file), "utf8").trim());

      if (parsed.license === undefined && texts.length === 0) {
        throw new Error(`${key} declares no licence and ships no licence file`);
      }

      const repository =
        parsed.repository === undefined
          ? null
          : (z.string().safeParse(parsed.repository).data ??
            z.object({ url: z.string() }).parse(parsed.repository).url);

      seen.set(key, {
        name: parsed.name,
        version: parsed.version,
        license: parsed.license ?? "see the licence text",
        source: repository ?? parsed.homepage ?? null,
        licenseTexts: texts,
      });
    }

    return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
  }
}

/** The package root of a bundled module, or null for the app's own and the workspace's code. */
export function packageDir(moduleId: string): string | null {
  const id = moduleId.replace(/^\0/u, "").split("?")[0] ?? "";
  const marker = "/node_modules/";
  const at = id.lastIndexOf(marker);

  if (at === -1) return null;

  const rest = id.slice(at + marker.length).split("/");
  const name = rest[0]?.startsWith("@") === true ? `${rest[0]}/${rest[1] ?? ""}` : (rest[0] ?? "");

  if (name === "" || name.startsWith(".")) return null;

  const dir = id.slice(0, at + marker.length + name.length);

  return existsSync(join(dir, "package.json")) ? dir : null;
}

function licenseFiles(dir: string): string[] {
  return readdirSync(dir)
    .filter((file) => /^(licen[cs]e|copying|notice)(\.|-|$)/iu.test(file))
    .sort();
}

const LGPL_NOTE = `The Kasten web app links OpenPGP.js as a library. OpenPGP.js is free software under the
GNU Lesser General Public License, version 3 or later. You may change or replace it: change the
openpgp version in packages/core/package.json, run "pnpm install", then rebuild the app with
"pnpm --filter @kasten/web build". The source of this version is at the address given above.
The LGPL adds permissions to the GNU General Public License, version 3, whose text is at the end
of this file.`;

/** The GNU GPL, version 3, unchanged from https://www.gnu.org/licenses/gpl-3.0.txt. */
const GPL_FILE = fileURLToPath(new URL("GPL-3.0.txt", import.meta.url));

/**
 * The source of exactly this version: the release tag of a GitHub repository. LGPL-3.0 section 4
 * needs the library's source, so the repository's front page is not enough. Other addresses stay
 * as they are.
 */
export function versionSource(source: string, version: string): string {
  const repo =
    /^(?:git\+)?(?:https?|git|ssh):\/\/(?:git@)?github\.com\/([^/]+\/[^/]+?)(?:\.git)?\/?$/u.exec(
      source,
    )?.[1];

  return repo === undefined ? source : `https://github.com/${repo}/tree/v${version}`;
}

/**
 * The text of THIRD_PARTY_LICENSES.txt. When a package is under the LGPL, the GPL text it builds
 * on follows once at the end (LGPL-3.0 section 4(b)).
 */
export function renderLicenses(
  packages: readonly BundledPackage[],
  gplText: () => string = () => readFileSync(GPL_FILE, "utf8"),
): string {
  const lines = [
    "Third-party software in the Kasten web app",
    "",
    "The Kasten web app is licensed under the Apache License 2.0. It bundles the packages below,",
    "each under its own licence. This file is generated by the build (web/scripts/licenses.ts).",
    "",
    ...packages.map((pkg) => `- ${pkg.name} ${pkg.version} (${pkg.license})`),
    "",
  ];

  const lgpl = packages.some((pkg) => pkg.license.includes("LGPL"));

  for (const pkg of packages) {
    const isLgpl = pkg.license.includes("LGPL");

    lines.push("=".repeat(78), `${pkg.name} ${pkg.version}`, `Licence: ${pkg.license}`);

    if (pkg.source !== null)
      lines.push(`Source: ${isLgpl ? versionSource(pkg.source, pkg.version) : pkg.source}`);

    if (isLgpl) lines.push("", LGPL_NOTE);

    lines.push("");

    if (pkg.licenseTexts.length === 0) lines.push("(The package ships no licence file.)", "");

    for (const text of pkg.licenseTexts) lines.push(text, "");
  }

  if (lgpl) {
    lines.push(
      "=".repeat(78),
      "GNU General Public License, version 3",
      "The GNU Lesser General Public License above adds permissions to this licence.",
      "",
      gplText().trim(),
      "",
    );
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

/** Records the modules of every chunk this build writes. */
export function collectLicenses(collector: LicenseCollector): Plugin {
  return {
    name: "kasten-collect-licenses",
    apply: "build",
    generateBundle(_options, bundle) {
      for (const output of Object.values(bundle)) {
        if (output.type !== "chunk") continue;

        for (const id of output.moduleIds) collector.add(id);
      }
    },
  };
}
